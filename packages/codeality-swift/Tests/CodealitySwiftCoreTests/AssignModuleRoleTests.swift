import Testing

@testable import CodealitySwiftCore

@Suite struct AssignModuleRoleTests {
  func role(
    _ path: String, _ text: String = "", extensionOnly: Bool = false,
    yaml: String = "roots: [Sources]\n"
  )
    throws -> ModuleRole
  {
    let fixture = Fixture()
    fixture.config(yaml)
    return try assignModuleRole(
      path: path, text: text, extensionOnly: extensionOnly,
      config: try loadConfig(projectRoot: fixture.root))
  }

  @Test func generatedPluginRegistrantIsGenerated() throws {
    #expect(try role("Runner/GeneratedPluginRegistrant.swift") == .generated)
  }

  @Test func aGeneratedMarkerCommentIsGenerated() throws {
    #expect(
      try role("Sources/A.swift", "// Generated by SwiftGen - do not edit\nstruct A {}\n")
        == .generated)
  }

  @Test func aDocCommentMentioningGeneratedCodeIsNotAMarker() throws {
    #expect(
      try role("Sources/A.swift", "/// Wraps the id generated by the server.\nstruct A {}\n")
        == .ordinary)
    #expect(
      try role("Sources/A.swift", "// Ids are generated by the server.\nstruct A {}\n") == .ordinary
    )
  }

  @Test func testsByNameOrDirectory() throws {
    #expect(try role("Sources/FooTests.swift") == .test)
    #expect(try role("Tests/Core/Foo.swift") == .test)
  }

  @Test func excludeGlobsWinOverEverything() throws {
    #expect(
      try role("Sources/Vendor/X.swift", yaml: "roots: [Sources]\nexclude: ['Sources/Vendor/**']\n")
        == .excluded)
  }

  @Test func extensionOnlyComesBeforeEntrypoint() throws {
    #expect(try role("Sources/Beat+Format.swift", extensionOnly: true) == .extensionOnly)
  }

  @Test func configuredEntrypoint() throws {
    let yaml = "roots: [Sources]\nroles:\n  entrypoint: [Sources/App.swift]\n"
    #expect(try role("Sources/App.swift", yaml: yaml) == .entrypoint)
    #expect(try role("Sources/Other.swift", yaml: yaml) == .ordinary)
  }
}
