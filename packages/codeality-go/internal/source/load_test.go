func moduleFS(files map[string]string) fstest.MapFS {
	fsys := fstest.MapFS{"go.mod": {Data: []byte("module example.com/demo\n\ngo 1.26.0\n")}}
	for name, content := range files {
		fsys[name] = &fstest.MapFile{Data: []byte(content)}
	}

	return fsys
}

func TestLoadAssignsRoles(t *testing.T) {
	t.Parallel()

	fsys := moduleFS(map[string]string{
		"cmd/demo/main.go":            "package main\n\nfunc main() {}\n",
		"internal/job/doc.go":         "// Package job is a fixture.\npackage job\n",
		"internal/job/lease.go":       "package job\n\ntype Lease struct{}\n",
		"internal/job/lease_text.go":  "package job\n\nfunc (l Lease) String() string { return \"\" }\n",
		"internal/job/lease_test.go":  "package job\n",
		"internal/job/errors.go":      "package job\n\nconst limit = 3\n",
		"internal/job/zz_gen.go":      "// Code generated by x. DO NOT EDIT.\n\npackage job\n",
		"internal/job/broken.go":      "package job\n\nfunc (\n",
		"internal/job/skipped.go":     "package job\n",
		"internal/job/testdata/x.go":  "package x\n",
		"vendor/v/v.go":               "package v\n",
		"nested/go.mod":               "module example.com/nested\n",
		"nested/n.go":                 "package nested\n",
		"internal/job/_draft/d.go":    "package d\n",
		"internal/job/README.md":      "not go",
		"internal/job/.hidden/h.go":   "package h\n",
		"internal/job/marker_late.go": "package job\n\n// Code generated by x. DO NOT EDIT.\nconst late = 1\n",
	})

	cfg := config.Default()
	cfg.Exclude = []string{"**/skipped.go"}
	cfg.Roles.Data = []string{"internal/job/errors.go"}

	module, err := source.Load(fsys, cfg)
	if err != nil {
		t.Fatal(err)
	}

	want := map[string]source.Role{
		"cmd/demo/main.go":            source.RoleEntrypoint,
		"internal/job/doc.go":         source.RoleDoc,
		"internal/job/lease.go":       source.RoleOrdinary,
		"internal/job/lease_text.go":  source.RoleMethodsOnly,
		"internal/job/lease_test.go":  source.RoleTest,
		"internal/job/errors.go":      source.RoleData,
		"internal/job/zz_gen.go":      source.RoleGenerated,
		"internal/job/broken.go":      source.RoleOrdinary,
		"internal/job/marker_late.go": source.RoleOrdinary,
	}

	got := make(map[string]source.Role, len(module.Files))
	for _, file := range module.Files {
		got[file.Path] = file.Role
	}

	if len(got) != len(want) {
		t.Errorf("loaded %d files, want %d: %v", len(got), len(want), got)
	}

	for name, role := range want {
		if got[name] != role {
			t.Errorf("role of %s = %q, want %q", name, got[name], role)
		}
	}

	if module.Path != "example.com/demo" || !module.HasCmd {
		t.Errorf("module = %q, HasCmd %v", module.Path, module.HasCmd)
	}

	if len(module.ByDir()["internal/job"]) != 8 {
		t.Errorf("ByDir grouped %d files in internal/job, want 8", len(module.ByDir()["internal/job"]))
	}
}

func TestLoadRecordsParseError(t *testing.T) {
	t.Parallel()

	module, err := source.Load(moduleFS(map[string]string{"a.go": "package a\n\nfunc (\n"}), config.Default())
	if err != nil {
		t.Fatal(err)
	}

	if module.Files[0].ParseErr == nil {
		t.Error("ParseErr is nil for a file that does not parse")
	}
}

func TestLoadRejectsConflictingRoles(t *testing.T) {
	t.Parallel()

	cfg := config.Default()
	cfg.Generated = []string{"a.go"}
	cfg.Roles.Data = []string{"a.go"}

	_, err := source.Load(moduleFS(map[string]string{"a.go": "package a\n"}), cfg)
	if _, ok := errors.AsType[*config.InvalidError](err); !ok {
		t.Fatalf("Load error = %v, want InvalidError", err)
	}
}

func TestLoadNeedsModule(t *testing.T) {
	t.Parallel()

	cases := map[string]fstest.MapFS{
		"missing go.mod":      {},
		"go.mod without path": {"go.mod": {Data: []byte("go 1.26.0\n")}},
	}

	for name, fsys := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			if _, err := source.Load(fsys, config.Default()); !errors.Is(err, source.ErrNoModule) {
				t.Fatalf("Load error = %v, want ErrNoModule", err)
			}
		})
	}
}
