#!/usr/bin/env python3
"""Regenerate lib/analysis_options.yaml and lib/flutter.yaml.

The upstream rule lists are inlined rather than included, so codeality_lints
has no dependencies and cannot fight a consumer's version solve. Run this when
bumping the upstream versions below, after `dart pub cache add` has fetched
them:

    python3 tool/generate.py
"""

import re
from pathlib import Path

LINTS = "6.1.0"
FLUTTER_LINTS = "6.0.0"
CACHE = Path.home() / ".pub-cache/hosted/pub.dev"
OUT = Path(__file__).resolve().parent.parent / "lib"

# Stagebeat's four rules come first; the rest are the codeality additions.
STRICT = [
    "prefer_final_locals",
    "prefer_const_constructors",
    "always_declare_return_types",
    "avoid_print",
    "avoid_dynamic_calls",
    "avoid_slow_async_io",
    "avoid_type_to_string",
    "cancel_subscriptions",
    "close_sinks",
    "directives_ordering",
    "literal_only_boolean_expressions",
    "no_adjacent_strings_in_list",
    "only_throw_errors",
    "prefer_final_fields",
    "prefer_final_in_for_each",
    "prefer_void_to_null",
    "test_types_in_equals",
    "throw_in_finally",
    "type_annotate_public_apis",
    "unawaited_futures",
    "unnecessary_await_in_return",
    "unnecessary_statements",
    "use_super_parameters",
]


def rules(path: Path) -> list[str]:
    return re.findall(r"^\s*-\s*([a-z_0-9]+)\s*$", path.read_text(), re.M)


def block(title: str, names: list[str]) -> str:
    return f"    # {title}\n" + "".join(f"    - {name}\n" for name in names)


def header(upstream: str) -> str:
    return f"""# codeality_lints - https://github.com/syntopica/codeality
#
# Inlines {upstream} rather than including them, so this package has no
# dependencies. Generated by tool/generate.py; do not edit by hand.

analyzer:
  language:
    strict-casts: true
    strict-inference: true
    strict-raw-types: true

linter:
  rules:
"""


def main() -> None:
    lints = CACHE / f"lints-{LINTS}/lib"
    base = sorted(set(rules(lints / "core.yaml") + rules(lints / "recommended.yaml")))
    flutter = rules(CACHE / f"flutter_lints-{FLUTTER_LINTS}/lib/flutter.yaml")
    flutter_only = sorted(set(flutter) - set(base))
    upstream = f"package:lints {LINTS} (core + recommended)"
    (OUT / "analysis_options.yaml").write_text(
        header(upstream)
        + block(upstream, base)
        + block("codeality strict additions", [r for r in STRICT if r not in base])
    )
    (OUT / "flutter.yaml").write_text(
        header(f"{upstream} and package:flutter_lints {FLUTTER_LINTS}")
        + block(upstream, base)
        + block(f"package:flutter_lints {FLUTTER_LINTS}", flutter_only)
        + block(
            "codeality strict additions",
            [r for r in STRICT if r not in base and r not in flutter_only],
        )
    )


if __name__ == "__main__":
    main()
