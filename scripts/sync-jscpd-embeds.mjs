#!/usr/bin/env node
// The Dart and Swift tools run jscpd themselves - their consumers have no
// Node workspace to run `baseline-dupes` from - so each embeds the shared
// defaults from packages/quality-config/jscpd.json and the jscpd version
// pinned in the root package.json. This regenerates those embedded copies so
// there is still one source of truth.
//
// Usage:
//   node scripts/sync-jscpd-embeds.mjs          write the embedded copies
//   node scripts/sync-jscpd-embeds.mjs --check  fail (exit 1) if any is stale; used in CI

import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { argv, exit } from 'node:process'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '..')

const config = JSON.parse(
  await readFile(
    resolve(REPO_ROOT, 'packages/quality-config/jscpd.json'),
    'utf8',
  ),
)
const rootPackage = JSON.parse(
  await readFile(resolve(REPO_ROOT, 'package.json'), 'utf8'),
)
const version = rootPackage.devDependencies.jscpd.replace(/^[\^~]/, '')

const quote = (value) =>
  `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

function dartSource() {
  const ignore = config.ignore.map((glob) => `    ${quote(glob)},`).join('\n')
  return `// Generated by scripts/sync-jscpd-embeds.mjs from
// packages/quality-config/jscpd.json. Do not edit by hand.

/// The shared jscpd defaults and the pinned jscpd version.
abstract final class JscpdDefaults {
  static const String version = ${quote(version)};
  static const int minTokens = ${config.minTokens};
  static const num threshold = ${config.threshold};
  static const List<String> ignore = [
${ignore}
  ];
}
`
}

function swiftSource() {
  const ignore = config.ignore
    .map((glob) => `    ${JSON.stringify(glob)},`)
    .join('\n')
  return `// Generated by scripts/sync-jscpd-embeds.mjs from
// packages/quality-config/jscpd.json. Do not edit by hand.

/// The shared jscpd defaults and the pinned jscpd version.
public enum JscpdDefaults {
  public static let version = ${JSON.stringify(version)}
  public static let minTokens = ${config.minTokens}
  public static let threshold: Double = ${config.threshold}
  public static let ignore: [String] = [
${ignore}
  ]
}
`
}

const TARGETS = [
  {
    packageDir: 'packages/codeality-dart',
    path: 'packages/codeality-dart/lib/src/assets/jscpd_defaults.dart',
    render: dartSource,
  },
  {
    packageDir: 'packages/codeality-swift',
    path: 'packages/codeality-swift/Sources/CodealitySwiftCore/Assets/JscpdDefaults.swift',
    render: swiftSource,
  },
]

const check = argv.includes('--check')
let stale = false
for (const target of TARGETS) {
  const file = resolve(REPO_ROOT, target.path)
  // A package that does not exist yet has nothing to embed into.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  if (!existsSync(resolve(REPO_ROOT, target.packageDir))) continue
  const expected = target.render()
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  const actual = existsSync(file) ? await readFile(file, 'utf8') : ''
  if (actual === expected) continue
  if (check) {
    console.error(`stale: ${target.path} - run pnpm sync-jscpd`)
    stale = true
  } else {
    // eslint-disable-next-line security/detect-non-literal-fs-filename
    await writeFile(file, expected)
    console.log(`wrote ${target.path}`)
  }
}
exit(stale ? 1 : 0)
